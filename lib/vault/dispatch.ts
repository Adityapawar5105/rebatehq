// The single door from the UI into the vault. Every command passes the role check
// (lib/roles/access.ts ACTION_CAP) before any query runs, so a role without a capability
// never receives the data behind it. The Web Worker and the browser test gate both use this.
import { ACTION_CAP } from "../roles/access";
import { storageStatus } from "./storage";
import { VaultError, type Request } from "./protocol";
import type { VaultService } from "./service";
import { msg } from "../i18n/core";
export type Hooks = { signal: () => AbortSignal; progress: (stage: string, done: string, total: string, kind?: import("../studio/studio").ProgressKind) => void; unlocked?: () => void };
export async function dispatch(service: VaultService, request: Request, hooks: Hooks): Promise<unknown> {
  if (!(request.action in ACTION_CAP)) throw new VaultError("PROTOCOL", msg("vault.dispatch.unsupportedLocalCommand2"));
  await service.guard(ACTION_CAP[request.action]);
  service.licenceGuard(request.action);
  const { progress } = hooks;
  switch (request.action) {
    case "reportState":return service.reportState();
    case "reportCheck":return service.reportCheck(request.data.kind,request.data.month,hooks.signal(),progress);
    case "reportExport":return service.reportExport(request.data.id,request.data.locale);
    case "roiV2":return service.roiV2();
    case "roiRows":return service.roiRows(request.data.kind,request.data.offset,request.data.grid);
    case "roiRecord":return service.roiRecord(request.data.input);
    case "roiVoid":return service.roiVoid(request.data.id);
    case "scorecard":return service.scorecard(request.data);
    case "scorecardOptIn":return service.scorecardOptIn(request.data.optIn);
    case "vendorSheets":return service.vendorSheets();
    case "vendorReview":return service.vendorReview(request.data.sheet,request.data.window,request.data.offset,request.data.grid);
    case "vendorReviewQuotes":return service.vendorReviewQuotes(request.data.sheet,request.data.offset,request.data.grid);
    case "vendorPpv":return service.vendorPpv({from:request.data.from,to:request.data.to},request.data.offset,request.data.grid);
    case "vendorPpvLines":return service.vendorPpvLines(request.data.product,{from:request.data.from,to:request.data.to},request.data.offset,request.data.grid);
    case "simOptions":return service.simOptions();
    case "relayLocal":return service.relayLocal();
    case "shareState":return service.shareState();
    case "shareCounts":return service.shareCounts();
    case "shareExport":return service.shareExport(request.data.packs,request.data.role,request.data.name);
    case "shareImportPreview":return service.shareImportPreview(request.data.file,request.data.code);
    case "shareImport":return service.shareImport(request.data.file,request.data.code);
    case "shareGrid":return service.shareGrid();
    case "shareGridSave":return service.shareGridSave(request.data.grid);
    case "shareGridDiscard":return service.shareGridDiscard();
    case "sharePublish":return service.sharePublish(hooks.signal());
    case "agentState":return service.agentState();
    case "agentRows":return service.agentRows(request.data.offset,request.data.grid);
    case "agentRun":return service.agentRun(hooks.signal(),progress);
    case "agentMark":return service.agentMark(request.data.key,request.data.status);
    case "agentSettingsSave":return service.agentSettingsSave(request.data.input);
    case "indexState":return service.indexState();
    case "indexSkus":return service.indexSkus(request.data.id,request.data.offset,request.data.grid);
    case "indexTriggerSave":return service.indexTriggerSave(request.data.input);
    case "indexTriggerDelete":return service.indexTriggerDelete(request.data.id);
    case "deadState":return service.deadState();
    case "benchState":return service.benchState();
    case "benchPreview":return service.benchPreview(request.data.quarter);
    case "benchMapSave":return service.benchMapSave(request.data.mapping);
    case "benchShared":return service.benchShared(request.data.payload, request.data.stored);
    case "benchFiguresSave":return service.benchFiguresSave(request.data.quarter, request.data.cells);
    case "benchWithdrawn":return service.benchWithdrawn();
    case "deadRows":return service.deadRows(request.data.offset, request.data.grid);
    case "deadSettingsSave":return service.deadSettingsSave(request.data.input);
    case "deadDraft":return service.deadDraft(request.data.ids);
    case "quoteGuidance":return service.quoteGuidance(request.data.id);
    case "quoteCrossSell":return service.quoteCrossSell(request.data.id);
    case "folderGet":return service.folderGet();
    case "folderSet":return service.folderSet(request.data.directory);
    case "studioFolder":return service.studioFolder(request.data.files);
    case "folderPickup":return service.folderPickup();
    case "supplierClaimBalance":return service.supplierClaimBalance(request.data.id);
    case "supplierPaymentRecord":return service.supplierPaymentRecord(request.data.input);
    case "supplierPaymentVoid":return service.supplierPaymentVoid(request.data.id);
    case "rebateFinanceExport":return service.rebateFinanceExport(request.data.format);
    case "folderPickupSet":return service.folderPickupSet(request.data.every, request.data.auto);
    case "simRun":return service.simRun(request.data.scenario,hooks.signal(),progress);
    case "simRows":return service.simRows(request.data.dim,request.data.offset,request.data.grid);
    case "supplierClaims":return service.supplierClaims(request.data.offset,request.data.grid);
    case "supplierPurchases":return service.supplierPurchases(request.data.offset,request.data.grid,request.data.claimId);
    case "supplierProgress":return service.supplierProgress(request.data.offset,request.data.grid);
    case "supplierClaimPreview":return service.supplierClaimPreview(request.data.id);
    case "supplierClaimSave":return service.supplierClaimSave(request.data.input);
    case "supplierClaimStatus":return service.supplierClaimStatus(request.data.id,request.data.status);
    case "supplierClaimExport":return service.supplierClaimExport(request.data.id,request.data.format,request.data.fingerprint);
    case "customerList":return service.customerList(request.data.offset,request.data.grid);
    case "productList":return service.productList(request.data.offset,request.data.grid);
    case "noteSet":return service.noteSet(request.data.kind,request.data.id,request.data.text);
    case "sourceRemovePreview":return service.sourceRemovePreview(request.data.id);
    case "gridTotals":return service.gridTotals(request.data.types,request.data.values);
    case "rebateProgress":return service.rebateProgress(request.data.offset,request.data.grid);
    case "rebateState":return service.rebateState();
    case "rebateRows":return service.rebateRows(request.data.id,request.data.offset,request.data.grid);
    case "rebateSave":return service.rebateSave(request.data.input);
    case "rebateDelete":return service.rebateDelete(request.data.id);
    case "rebateRecalculate":return service.rebateRecalculate();
    case "currencySet": return service.currencySet(request.data.currency);
    case "homeMonitor": return service.homeMonitor(request.data.thresholdBp);
    case "competitorList": return service.competitorList(request.data.product,request.data.customer);
    case "competitorAdd": return service.competitorAdd(request.data.input);
    case "priceGrid": return service.priceGrid(request.data.offset,request.data.search,request.data.grid);
    case "priceGridPaste": return service.priceGridPaste(request.data.text,request.data.keys,request.data.start);
    case "priceGridDraft": return service.priceGridDraft(request.data.edits,request.data.revision);
    case "ruleWhatIf": return service.ruleWhatIf(request.data.id,request.data.increase,request.data.exact);
    case "priceLandedState": return service.priceLandedState(request.data.id,request.data.offset,request.data.grid);
    case "priceLandedCheck": return service.priceLandedCheck(request.data.receipt,request.data.file,hooks.signal());
    case "serviceOrders": return service.serviceOrders(request.data.offset,request.data.grid);
    case "serviceFlag": return service.serviceFlag(request.data.key,request.data.free);
    case "relayView":case "relayRegister":case "relayJoin":case "relayRotate":case "relaySync":case "relayShare":case "relayRequest":case "relayDecide":case "relayComment":case "relayRetry":case "relayDiscard":return service.relay(request,hooks.signal());
    case "home": return service.home();
    case "checklist": return service.checklist();
    case "checklistMark": return service.checklistMark(request.data.step);
    case "roleList": return service.roleList();
    case "roleSet": return service.roleSet(request.data.userId, request.data.name, request.data.role);
    case "roleRemove": return service.roleRemove(request.data.userId);
    case "rolePreview": return service.rolePreview(request.data.role);
    case "cleanupScan": return service.cleanupScan();
    case "cleanupHistory": return service.cleanupHistory();
    case "cleanupApply": return service.cleanupApply(request.data.kind, request.data.key, request.data.target ?? null);
    case "cleanupUndo": return service.cleanupUndo(request.data.id);
    case "cleanupMergeAll": return service.cleanupMergeAll(progress);
    case "cleanupUndoMany": return service.cleanupUndoMany(request.data.ids);
    case "costBasis": return service.costBasis();
    case "costBasisSet": return service.costBasisSet(request.data.group, request.data.basis);
    case "marginBridge": return service.marginBridge(request.data.input);
    case "priceOpsState": return service.priceOpsState();
    case "priceExceptions": return service.priceExceptions(request.data.input);
    case "priceExpiry": return service.priceExpiry(request.data.days,request.data.asOf,request.data.offset,request.data.grid);
    case "pricePlan": return service.pricePlan(request.data.input);
    case "priceRollback": return service.priceRollback(request.data.version);
    case "priceLetter": return service.priceLetter(request.data.id,request.data.locale);
    case "pricingState": return service.pricingState();
    case "pricingOwner": return service.pricingOwner(request.data.name, request.data.userId, request.data.backupDays);
    case "guardSet": return service.guardSet(request.data.input);
    case "ruleSave": return service.ruleSave(request.data.input);
    case "ruleSimulate": return service.ruleSimulate(request.data.id);
    case "rulePreview": return service.rulePreview(request.data.id, request.data.offset, request.data.grid);
    case "ruleApprove": return service.ruleApprove(request.data.id);
    case "priceExport": return service.priceExport(request.data.id, request.data.profile, request.data.format, request.data.layout);
    case "exportLayouts": return service.exportLayouts();
    case "simSaved": return service.simSaved();
    case "simSave": return service.simSave(request.data.name);
    case "simSavedDelete": return service.simSavedDelete(request.data.id);
    case "exportLayoutSave": return service.exportLayoutSave(request.data.input, request.data.id);
    case "exportLayoutDelete": return service.exportLayoutDelete(request.data.id);
    case "backupStatus": return service.backupStatus();
    case "backupConfigure": return service.backupConfigure(request.data.directory, request.data.hours);
    case "backupNow": return service.backupNow();
    case "backupExport": return service.backupExport();
    case "backupRestore": return service.backupRestore(request.data.file, request.data.passphrase);
    case "capacityUpgrade": return service.capacityUpgrade();
    case "licenceSet": return service.licenceSet(request.data.envelope,request.data.device,request.data.offline);
    case "init": return service.init(request.data.scope);
    case "create": {
      // A vault always starts with a named Pricing Owner; the worker refuses to create one without.
      if (typeof request.data.ownerName !== "string" || !request.data.ownerName.trim()) throw new VaultError("OWNER", msg("vault.dispatch.nameThePricingOwner"));
      return service.create(request.data.passphrase, request.data.tier, request.data.ownerName);
    }
    case "unlock": { const result = await service.unlock(request.data.passphrase); hooks.unlocked?.(); return result; }
    case "lock": return service.lock();
    case "touch": return service.touch();
    case "status": return service.status();
    case "save": return service.save();
    case "verify": return service.verify();
    case "storage": return storageStatus();
    case "studioAdd": return service.studioAdd(request.data.files, request.data.replaces ?? null);
    case "studioUpdate": return service.studioUpdate(request.data.id, request.data.settings, request.data.role, { erp: request.data.erp, field: request.data.field, confirmed: request.data.confirmed, range: request.data.range });
    case "studioDrop": return service.studioDrop(request.data.id);
    case "studioClear": return service.studioClear();
    case "studioState": return service.studioState();
    case "studioPlan": return service.studioPlan(hooks.signal(), progress);
    case "studioCommit": return service.studioCommit(request.data.acknowledge, progress);
    case "studioDownload": return service.studioDownload(request.data.id, hooks.signal());
    case "studioZip": return service.studioZip(hooks.signal());
    case "recipeSave": return service.recipeSave(request.data.id, request.data.name);
    case "recipeApply": return service.recipeApply(request.data.id, request.data.recipeId);
    case "sources": return service.sources();
    case "sourceRemove": return service.sourceRemove(request.data.id);
    case "fixGroups": return service.fixGroups();
    case "fixRows": return service.fixRows(request.data.sourceId, request.data.code, request.data.offset ?? 0);
    case "fixSet": return service.fixSet(request.data.sourceId, request.data.code, request.data.field, request.data.value, request.data.rows ?? null);
    case "fixDismiss": return service.fixDismiss(request.data.sourceId, request.data.code, request.data.rows ?? null);
    case "fixRecheck": return service.fixRecheck(request.data.sourceId, request.data.code);
    case "health": return service.health();
    case "playgroundLoad": return service.playgroundLoad(progress);
    case "playgroundRemove": return service.playgroundRemove();
    case "creditsLoad": return service.creditsLoad(request.data.sourceId);
    case "marginWaterfall": return service.marginWaterfall(request.data.filters);
    case "marginDrill": return service.marginDrill(request.data.dim, request.data.filters, request.data.sort, request.data.grid);
    case "marginWhale": return service.marginWhale(request.data.filters);
    case "marginMath": return service.marginMath(request.data.metric, request.data.filters, request.data.offset ?? 0, request.data.grid);
    case "leaks": return service.leaks();
    case "leakRows": return service.leakRows(request.data.id, request.data.offset ?? 0, request.data.grid);
    case "leakReport": return service.leakReport(request.data.locale, request.data.ids);
    case "search": return service.search(request.data.text);
    case "priceCheck": return service.priceCheck(request.data.productId, request.data.customerId, request.data.quantity);
    case "quoteCreate": return service.quoteCreate(request.data.customerId);
    case "quoteLines": return service.quoteLines(request.data.id, request.data.lines);
    case "quoteSubmit": return service.quoteSubmit(request.data.id, request.data.reason);
    case "quoteWithdraw": return service.quoteWithdraw(request.data.id);
    case "quoteCopy": return service.quoteCopy(request.data.id);
    case "quoteRevise": return service.quoteRevise(request.data.id);
    case "quoteValidity": return service.quoteValidity(request.data.id, request.data.validUntil);
    case "quotePdf": return service.quotePdf(request.data.id, request.data.locale);
    case "brandingGet": return service.brandingGet();
    case "brandingSet": return service.brandingSet(request.data.input);
    case "priceList": return service.priceList(request.data.customerId, request.data.format);
    case "priceMailing": return service.priceMailing(request.data.runId);
    case "vaultReset": return service.vaultReset();
    case "passphraseChange": return service.passphraseChange(request.data.current, request.data.next);
    case "quoteDecide": return service.quoteDecide(request.data.id, request.data.decision, request.data.note);
    case "quoteGet": return service.quoteGet(request.data.id);
    case "quoteOutcome": return service.quoteOutcome(request.data.id, request.data.input);
    case "winLoss": return service.winLoss(request.data);
    case "auditPack": return service.auditPack(request.data.locale);
    case "templateVendors": return service.templateVendors();
    case "negotiationSheet": return service.negotiationSheet(request.data.vendor, request.data.locale);
    case "rebateAgreement": return service.rebateAgreement(request.data.id, request.data.locale);
    case "quoteList": return service.quoteList(!!request.data.pendingOnly);
    case "quoteShare": return service.quoteShare(request.data.id, request.data.preset, hooks.signal());
    case "quoteRelaySync": return service.quoteRelaySync(request.data.id, hooks.signal());
    case "roi": return service.roi();
    case "reconcile": return service.reconcile();
    case "reconAccept": return service.reconAccept(request.data.id ?? null);
    case "reconRebuild": return service.reconRebuild();
    default: throw new VaultError("PROTOCOL", msg("vault.dispatch.unsupportedLocalCommand"));
  }
}
